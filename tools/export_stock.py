#!/usr/bin/env python3
"""Export the demo stock levels for the static preview.

Vercel and GitHub Pages serve the storefront without the Python API, so the shop
cannot ask the database which products are sold out. This writes a tiny script
with the deterministic seed's stock so api.js can fall back to it, keeping the
static preview faithful to the app.

Run by tools/build-static.sh; the output is git-ignored.
"""
import json
import os
import pathlib
import sys
import tempfile
from datetime import datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
tmp = pathlib.Path(tempfile.mkdtemp(prefix="unimart-snapshot-"))
os.environ["FC_DB"] = str(tmp / "snapshot.db")
os.environ["FC_QUIET"] = "1"
sys.path.insert(0, str(ROOT))

import server  # noqa: E402  (import after FC_DB is set)

server.init_db(reset=True)
conn = server.connect()
rows = conn.execute(
    "SELECT id, price, stock, min_stock FROM products WHERE active = 1").fetchall()
items = [
    {"id": r["id"], "price": r["price"], "stock": r["stock"],
     "sold_out": r["stock"] <= 0, "low": 0 < r["stock"] <= r["min_stock"]}
    for r in rows
]
conn.close()

out = ROOT / "js" / "stock-snapshot.js"
payload = {"generated_at": datetime.now().isoformat(timespec="seconds"), "items": items}
out.write_text(
    "/* Generated by tools/export_stock.py for the static preview - do not edit. */\n"
    "window.UNIMART_SNAPSHOT = " + json.dumps(payload, separators=(",", ":")) + ";\n"
)
sold_out = sum(1 for i in items if i["sold_out"])
print(f"stock snapshot: {len(items)} products, {sold_out} sold out")
